/* Builds src/i18n.js: the Greek text is the key, English the translation.
   Landscape keys come straight from legacy/landscapes.js (same order as
   tools/landscapes-en.txt); interface phrases from tools/ui-en.tsv.
   Usage: node tools/make-i18n.cjs */
'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..');
const L=require('../legacy/landscapes.js'),T=require('../src/theory-map.js'),P=require('../src/path-engine.js');
const greek=/[α-ωΑ-Ωά-ώ]/;
const keys=[];const seen=new Set();
const add=s=>{if(s&&greek.test(s)&&!seen.has(s)){seen.add(s);keys.push(s);}};
for(const l of L.LANDSCAPES){add(l.name);add(l.short);add(l.idea);add(l.chordWarning);
  for(const c of l.colors){add(c.name);add(c.why);}
  for(const p of l.progressions){add(p.name);add(p.why);}
  for(const a of (l.addColor||[])){add(a.name);add(a.why);}}
for(const x of T.transformations(T.triad(0,'major'))){add(x.short);add(x.detail);}
for(const g of P.GOALS){add(g.label);add(g.intro);}
for(const k of Object.keys(T.MODE))add(T.MODE[k].label);
const en=fs.readFileSync(path.join(__dirname,'landscapes-en.txt'),'utf8').split('\n').filter(x=>x.length);
if(en.length!==keys.length)throw Error(`landscapes-en.txt has ${en.length} lines, expected ${keys.length}`);
const map={};
const put=(k,v,src)=>{if(Object.prototype.hasOwnProperty.call(map,k)&&map[k]!==v)throw Error(`Conflicting translation for «${k}» (${src}): «${map[k]}» vs «${v}»`);map[k]=v;};
keys.forEach((k,i)=>put(k,en[i],'landscapes'));
for(const line of fs.readFileSync(path.join(__dirname,'ui-en.tsv'),'utf8').split('\n')){
  if(!line)continue;const [k,v]=line.split('\t');if(v===undefined)throw Error('Bad line: '+line);put(k,v,'ui');
}
const js=`/* Chord Lab Studio · Greek and English. Generated by tools/make-i18n.cjs:
   edit tools/ui-en.tsv or tools/landscapes-en.txt, then rerun it.
   The Greek text is the key; {0}, {1} … are placeholders. */
(function(root,factory){const api=factory();if(typeof module==='object'&&module.exports)module.exports=api;else root.I18N=api;})(typeof globalThis!=='undefined'?globalThis:this,function(){
'use strict';
const EN=${JSON.stringify(map,null,0).replace(/","/g,'",\n"')};
const fill=(s,args)=>args.length?String(s).replace(/\\{(\\d+)\\}/g,(m,i)=>args[i]!==undefined?String(args[i]):m):s;
/* One phrase. */
function L(lang,s,...args){return fill(lang==='en'&&Object.prototype.hasOwnProperty.call(EN,s)?EN[s]:s,args);}
/* A label joined with « · » (style · path, centre · mode …): each part on its own. */
function parts(lang,s){
  if(lang!=='en'||s==null)return s;
  if(Object.prototype.hasOwnProperty.call(EN,s))return EN[s];
  return String(s).split(' · ').map(p=>Object.prototype.hasOwnProperty.call(EN,p)?EN[p]:p).join(' · ');
}
/* Known names inside longer text: mode names in key names, «χρ.» in degrees. */
const INLINE=Object.keys(EN).filter(k=>/ \\/ /.test(k)).map(k=>[k,EN[k]]).concat([['χρωμ.','chr.'],['χρ.','chr.'],[' · χρώμα',' · colour']]);
function inline(lang,s){if(lang!=='en'||s==null)return s;let out=String(s);for(const [a,b] of INLINE)out=out.split(a).join(b);return out;}
function detect(stored,languages){
  if(stored==='el'||stored==='en')return stored;
  const first=(languages&&languages[0])||'el';
  return /^el\\b/i.test(first)?'el':'en';
}
return {EN,L,parts,inline,detect};
});
`;
fs.writeFileSync(path.join(root,'src','i18n.js'),js);
console.log(`src/i18n.js: ${Object.keys(map).length} phrases (${keys.length} from the landscapes)`);
